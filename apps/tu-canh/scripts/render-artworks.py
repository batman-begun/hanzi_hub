"""Prebuild display and high-resolution download artwork from one composition.
Public-domain originals retained in content/. Typography rendered using fonts,
never generated by an image model. No upscaling beyond source crop resolution.
"""
import json,pathlib,math
from PIL import Image,ImageOps,ImageDraw,ImageFont
p=pathlib.Path(__file__).resolve().parents[1]
cn=str(p/'content/NotoSerifCJKsc-Regular.otf')
# Override these paths in another environment; see README.
import os
cn=os.environ.get('TU_CANH_CJK_FONT',cn)
latin=os.environ.get('TU_CANH_LATIN_FONT','/usr/share/fonts/truetype/dejavu/DejaVuSerif.ttf')
sources=json.loads((p/'content/art-sources.json').read_text());sources=[s for s in sources if 'error' not in s]
byid={s['id']:s for s in sources}
# Pilot assignments are editorial, not a random image/quote pairing.
assign=[54677,72711,37325,54701,56385,37325,56070,54114,56385,54677,37325,54701,56240,72711,56070,56385,54677,54701,54114,72711]
doc=json.loads((p/'dist/quotes.json').read_text())
(p/'dist/assets').mkdir(exist_ok=True);(p/'dist/downloads').mkdir(exist_ok=True)
def font(path,size):return ImageFont.truetype(path,max(8,int(size)))
def wrap(draw,text,font,width,chinese=False):
 lines=[];line='';parts=list(text) if chinese else text.split(' ')
 for word in parts:
  trial=line+('' if chinese or not line else ' ')+word
  if draw.textlength(trial,font=font)>width and line:
   lines.append(line);line=word
  else:line=trial
 if line:lines.append(line)
 return lines
manifest=[]
for i,q in enumerate(doc['quotes']):
 s=byid[assign[i]];original=Image.open(p/s['file']).convert('RGB')
 w=min(2160,original.width,int(original.height*9/16));h=int(w*16/9)
 im=ImageOps.fit(original,(w,h),method=Image.Resampling.LANCZOS,centering=(.5,.5)).convert('RGBA')
 shade=Image.new('RGBA',(w,h));sd=ImageDraw.Draw(shade)
 for y in range(h):
  t=max(0,min(1,(y/h-.27)/.66));sd.line((0,y,w,y),fill=(7,26,24,int(18+215*t)))
 im=Image.alpha_composite(im,shade);dr=ImageDraw.Draw(im);scale=w/1080
 margin=int(w*.09);avail=w-2*margin
 ch=font(cn,68*scale);py=font(latin,27*scale);vi=font(latin,39*scale)
 chlines=wrap(dr,q['hanzi'],ch,avail,True);pylines=wrap(dr,q['pinyin'],py,avail);vilines=wrap(dr,q['vietnamese'],vi,avail)
 total=len(chlines)*98*scale+40*scale+len(pylines)*45*scale+75*scale+len(vilines)*62*scale
 y=min(h*.54,h*.85-total);y=max(h*.34,y)
 for line in chlines:dr.text((margin,y),line,font=ch,fill='#fff6e5',stroke_width=0);y+=98*scale
 y+=30*scale
 for line in pylines:dr.text((margin,y),line,font=py,fill='#e4dac7');y+=45*scale
 y+=35*scale;dr.line((margin,y,margin+60*scale,y),fill='#d7bd91',width=max(1,int(scale*2)));y+=35*scale
 for line in vilines:dr.text((margin,y),line,font=vi,fill='#f4ecdd');y+=62*scale
 # Founder-selected watermark A, bottom left, same composition for both exports.
 x=margin;yy=h*.92;box=int(64*scale);ink=(242,234,215,210)
 dr.rounded_rectangle((x,yy,x+box,yy+box),radius=2*scale,outline=ink,width=max(1,int(2*scale)))
 dr.text((x+8*scale,yy+5*scale),'词',font=font(cn,25*scale),fill=ink)
 dr.text((x+33*scale,yy+29*scale),'境',font=font(cn,25*scale),fill=ink)
 dr.text((x+82*scale,yy),'Từ Cảnh',font=font(latin,32*scale),fill=ink)
 dr.text((x+84*scale,yy+42*scale),'词 境',font=font(cn,15*scale),fill=ink)
 target=p/f"dist/downloads/{q['id']}.jpg";im.convert('RGB').save(target,quality=95,subsampling=0)
 screen=im.convert('RGB');screen.thumbnail((1080,1920),Image.Resampling.LANCZOS);screen.save(p/f"dist/assets/{q['id']}.webp",quality=88)
 q['image']=f"assets/{q['id']}.webp";q['download']=f"downloads/{q['id']}.jpg";q['image_group']=str(s['id']);q['artwork_baked']=True;q['width']=w;q['height']=h;q['source']=dict(s);q['source'].pop('file',None);q['art_alt']=f"{s['title']} — {s['artist']}";q['download_allowed']=True
 manifest.append(dict(id=q['id'],width=w,height=h,source_id=s['id'],download=q['download']))
(p/'dist/quotes.json').write_text(json.dumps(doc,ensure_ascii=False,indent=2));(p/'content/render-manifest.json').write_text(json.dumps(manifest,indent=2))
print('Rendered',len(manifest),'paired display/download artworks. No source-resolution upscaling.')
